/**
 * Tự động khởi tạo danh sách 56 ghế (40–60 ghế) với 3 loại theo đúng HD.md:
 * - STANDARD (hàng A–C): basePrice
 * - VIP (hàng D–F, cộng thêm 20.000đ): basePrice + 20.000đ
 * - COUPLE (hàng G, nhân đôi giá gốc + phụ thu): basePrice * 2 + 20.000đ
 */
export function generateSeatingLayout(showtimeId: string, basePrice: number = 90000): Seat[] {
  const rows = ['A', 'B', 'C', 'D', 'E', 'F', 'G'];
  const seatsPerRow = 8;
  const seats: Seat[] = [];

  rows.forEach((row) => {
    let type: 'STANDARD' | 'VIP' | 'COUPLE' = 'STANDARD';
    let tier: 'standard' | 'premium' | 'vip' = 'standard';
    let surcharge = 0;

    if (row === 'D' || row === 'E' || row === 'F') {
      type = 'VIP';
      tier = 'premium';
      surcharge = 20000;
    } else if (row === 'G') {
      type = 'COUPLE';
      tier = 'vip';
      surcharge = basePrice + 20000;
    }

    const price = basePrice + surcharge;

    for (let seatNum = 1; seatNum <= seatsPerRow; seatNum++) {
      const seatCode = `${row}${seatNum}`;
      seats.push({
        id: seatCode,
        seatCode,
        row,
        number: seatNum,
        type,
        surcharge,
        tier,
        price,
        status: 'AVAILABLE',
        state: 'available',
        lockedBy: null,
        lockedUntil: null,
      });
    }
  });

  return seats;
}

